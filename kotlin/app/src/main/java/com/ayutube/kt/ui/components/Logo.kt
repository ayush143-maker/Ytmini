/** The full static logo, used in the Home header. */
@Composable
fun AyuLogoLockup(modifier: Modifier = Modifier, height: Dp = 26.dp) {
    val ratio = remember { AyuLogo.WIDTH / AyuLogo.HEIGHT }

    Canvas(modifier.height(height).aspectRatio(ratio)) {
        val k = size.width / AyuLogo.WIDTH

        withTransform({
            scale(k, k, Offset.Zero)
            translate(-AyuLogo.X0, -AyuLogo.Y0)
        }) {
            drawMascot()
            drawWord { for (letter in AyuLogo.letters) drawPath(letter, AyuLogo.WordColor) }
        }
    }
}

/** Runs [block] in the wordmark's own (smaller, shifted) space. */
internal fun DrawScope.drawWord(block: DrawScope.() -> Unit) {
    withTransform({
        translate(AyuLogo.WORD_X0, AyuLogo.WORD_CY)
        scale(AyuLogo.WORD_SCALE, AyuLogo.WORD_SCALE, Offset.Zero)
        translate(-AyuLogo.WORD_SRC_X0, -AyuLogo.WORD_CY)
    }, block)
}

internal fun DrawScope.drawLogoLetter(index: Int, alpha: Float) {
    val a = alpha.coerceIn(0f, 1f)

    if (a > 0f) drawWord { drawPath(AyuLogo.letters[index], AyuLogo.WordColor, alpha = a) }
}

/** The mascot in white with a faint pink at the bottom, on whatever is behind it (never a pink tile). */
internal fun DrawScope.drawMascot(alpha: Float = 1f) {
    drawPath(
        AyuLogo.mark,
        Brush.verticalGradient(
            listOf(AyuLogo.MascotTop, AyuLogo.MascotBottom),
            startY = AyuLogo.Y0,
            endY = AyuLogo.Y1
        ),
        alpha = alpha
    )
}
